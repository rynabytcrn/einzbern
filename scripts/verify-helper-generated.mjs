import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtemp, readdir, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { HELPER_KEPT_FILES, REPOSITORY_ROOT, renderHelperDocs } from "./render-helper-docs.mjs";

async function files(root, prefix = "") {
  const result = [];
  for (const entry of await readdir(join(root, prefix), { withFileTypes: true })) {
    if (entry.name === ".git" || entry.name === "node_modules") continue;
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    assert.ok(entry.isFile() || entry.isDirectory(), `Non-regular entry: ${path}`);
    if (entry.isDirectory()) result.push(...await files(root, path));
    else result.push(path);
  }
  return result.sort();
}

export async function verifyHelperGenerated(helper) {
  const source = JSON.parse(await readFile(join(helper, ".github/engine-source.json"), "utf8"));
  const manifest = JSON.parse(await readFile(join(helper, "package.json"), "utf8"));
  assert.equal(source.schemaVersion, "einzbern.helper-source.v1");
  assert.equal(source.repository, "tpmoonchefryan/einzbern");
  assert.match(source.commit, /^[0-9a-f]{40}$/u);
  assert.equal(source.commit, execFileSync("git", ["-C", REPOSITORY_ROOT, "rev-parse", "HEAD"], { encoding: "utf8" }).trim(), "The generator checkout must match the immutable source reference");
  assert.equal(source.renderVersion, manifest.version, "Package and rendered version differ");
  const scratch = await mkdtemp(join(tmpdir(), "einzbern-helper-ci-"));
  try {
    const report = await renderHelperDocs({ out: scratch, version: source.renderVersion });
    const actual = (await files(helper)).filter((path) => !HELPER_KEPT_FILES.includes(path));
    assert.deepEqual(actual, report.files, "Missing or unowned distribution files");
    for (const path of report.files) {
      assert.deepEqual(await readFile(join(helper, path)), await readFile(join(scratch, path)), `Generated bytes differ: ${path}`);
      if (path.endsWith(".mjs")) execFileSync(process.execPath, ["--check", join(helper, path)], { stdio: "pipe" });
    }
    const archive = execFileSync(process.execPath, [join(helper, "skill/mana-orchestrate/scripts/create-skill-archive.mjs"), "--check"], { encoding: "utf8" }).trim();
    assert.match(archive, /^[0-9a-f]{64}$/u);
    return { ok: true, reasonCode: "HELPER_GENERATED_VERIFIED", source, files: report.files, archiveSha256: archive };
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  assert.equal(process.argv.length, 4);
  assert.equal(process.argv[2], "--helper");
  process.stdout.write(`${JSON.stringify(await verifyHelperGenerated(resolve(process.argv[3])))}\n`);
}
