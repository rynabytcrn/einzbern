#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
//
// Generate auditable, ordinary-file launchers for a machine-level portal
// installation. The paths are intentionally absolute: a launcher should make
// its target visible in review. TCRN-CROSS-STORY-482 R3: Atelier opens the libraries
// this device has registered, so a launcher carries at most --library (one registered
// library's absolute path, the one it opens first). Without it the portal opens the
// library of the directory the launcher runs in, then the machine's default library,
// then the first registered one; the page switches among the rest.
// TCRN-CROSS-STORY-526 (TCRN-CROSS-SUB-454): a launcher names no actor. Atelier writes as
// TCRN_PORTAL_ACTOR, which the launcher passes on from the environment it runs in; where that
// environment does not set it, Atelier refuses to start (PORTAL_ACTOR_REQUIRED, exit code 2).

import { chmod, lstat, stat, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const portalRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const platformRoot = dirname(portalRoot);

function argument(name, fallback = "") {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 && index + 1 < process.argv.length ? process.argv[index + 1] : fallback;
}

function fail(reasonCode, detail, message = reasonCode) {
  process.stderr.write(`${JSON.stringify({ ok: false, reasonCode, ...detail, error: message })}\n`);
  process.exit(2);
}

function absolute(name, value) {
  if (!isAbsolute(value)) fail("PORTAL_LAUNCHER_PATH_NOT_ABSOLUTE", { name, value }, `${name} must be absolute: ${value}`);
  return resolve(value);
}

function shellQuote(value) {
  return "'" + value.split("'").join("'\"'\"'") + "'";
}

function cmdQuote(value) {
  return `"${value.replaceAll("\"", "\\\"")}"`;
}

const outputDir = absolute("output-dir", argument("output-dir", platformRoot));
const libraryArgument = argument("library", "");
const library = libraryArgument === "" ? "" : absolute("library", libraryArgument);
const port = argument("port", "4319");
if (!/^\d+$/u.test(port) || Number(port) < 0 || Number(port) > 65535) {
  fail("PORTAL_LAUNCHER_PORT_INVALID", { port }, `port must be an integer from 0 to 65535: ${port}`);
}

try {
  if (!(await stat(outputDir)).isDirectory()) fail("PORTAL_LAUNCHER_OUTPUT_UNAVAILABLE", { outputDir }, `output directory is not a directory: ${outputDir}`);
} catch {
  fail("PORTAL_LAUNCHER_OUTPUT_UNAVAILABLE", { outputDir }, `output directory does not exist: ${outputDir}`);
}

const portalScript = join(portalRoot, "portal.mjs");
const nodeExecutable = process.execPath;
const targets = `portal=${portalScript}; library=${library || "chosen from the registry at start"}`;
const pathsComment = `# Generated by Atelier. Absolute targets: ${targets}.`;
const actorNote = "Atelier writes as TCRN_PORTAL_ACTOR from this environment and refuses to start without it.";
const shellLibrary = library ? ` --library ${shellQuote(library)}` : "";
const cmdLibrary = library ? ` --library ${cmdQuote(library)}` : "";
const commandLauncher = [
  "#!/bin/sh",
  pathsComment,
  `# ${actorNote}`,
  "set -eu",
  `exec ${shellQuote(nodeExecutable)} ${shellQuote(portalScript)}${shellLibrary} --port ${shellQuote(port)}`,
  "",
].join("\n");
const linuxLauncher = commandLauncher.replace("#!/bin/sh\n", "#!/bin/sh\n");
const windowsLauncher = [
  "@echo off",
  `rem Generated by Atelier. Absolute targets: ${targets}.`,
  `rem ${actorNote}`,
  `${cmdQuote(nodeExecutable)} ${cmdQuote(portalScript)}${cmdLibrary} --port ${cmdQuote(port)}`,
  "if errorlevel 1 exit /b %errorlevel%",
  "",
].join("\r\n");

const files = [
  { name: "atelier.command", content: commandLauncher, mode: 0o755 },
  { name: "atelier.sh", content: linuxLauncher, mode: 0o755 },
  { name: "atelier.cmd", content: windowsLauncher, mode: 0o644 },
];

for (const file of files) {
  const target = join(outputDir, file.name);
  try {
    const existing = await lstat(target);
    if (existing.isSymbolicLink()) fail("PORTAL_LAUNCHER_SYMLINK_REFUSED", { target }, `refusing to replace symlink: ${target}`);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  await writeFile(target, file.content, { encoding: "utf8", mode: file.mode });
  await chmod(target, file.mode);
  const created = await lstat(target);
  if (!created.isFile() || created.isSymbolicLink()) fail("PORTAL_LAUNCHER_NOT_REGULAR_FILE", { target }, `launcher is not a regular file: ${target}`);
}

process.stdout.write(`${JSON.stringify({
  ok: true,
  reasonCode: "PORTAL_LAUNCHERS_GENERATED",
  outputDir,
  portalScript,
  library: library || null,
  files: files.map(({ name }) => join(outputDir, name)),
  symlinks: false,
}, null, 2)}\n`);
